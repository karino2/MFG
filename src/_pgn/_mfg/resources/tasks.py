def update_trans_cpp(hpp, ecsname, cpp, funcName):
  """
  hpp: enum classのあるファイルのパス(例: "../mfg_resource.hpp")
  ecsname: enum classの名前(例: "ResId")
  cpp: コメントを追加するcppのパス(例: "../mfg_resource_trans_str.cpp")
  funcName: コメントを追加する関数名（例: "ResourceStringGen")

  mfg_resource.hppのenumのIDにあって、mfg_resource_trans_str.cppの言語ごと（及び最後のデフォルト言語）のcaseに無いものを、
  以下のようなC++コメントとして追加する
  // case ResId::SOME_ID: return "";
  """  
  ids = collect_enum_ids(hpp, ecsname)
  res = update_trans_str_case(cpp, ecsname, funcName, ids)
  with open(cpp, 'w', encoding='utf_8_sig') as fcpp:
    fcpp.write(res)

