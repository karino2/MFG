def gen_res_map(csname, idlist, gvarName):
  """
  以下のような文字列からenum idのlookupをするmapを生成。
  static const std::map<std::string, ResId> g_resMap{
    {"OFFSET_IS_OUTSIDE_OF_SOURCE_SIZE", ResId::OFFSET_IS_OUTSIDE_OF_SOURCE_SIZE},
    ...
  };

  ここでcsnameはResIdに、gvarNameはg_resMapに対応する。
  """
  builder = []
  builder.append(f"static const std::map<std::string, {csname}> {gvarName}{{")
  for id in idlist:
    builder.append('  {{"{0}", {1}::{0}}},'.format(id, csname))
  builder.append("};")
  return "\n".join(builder)

def gen_rev_ecs_map(csname, idlist, gvarName):
  """
  以下のような文字列からenum idのlookupをするmapを生成。
  static const std::map<TokenType, std::string> g_revMap{
    {TokenType::UNKNOWN, "OFFSET_IS_OUTSIDE_OF_SOURCE_SIZE"},
    ...
  };

  ここでcsnameはTokenTypeに、gvarNameはg_revMapに対応する。
  """
  builder = []
  builder.append(f"static const std::map<{csname}, std::string> {gvarName}{{")
  for id in idlist:
    builder.append('  {{{1}::{0}, "{0}"}},'.format(id, csname))
  builder.append("};")
  return "\n".join(builder)


