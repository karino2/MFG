def collect_enum_ids(fpath, ecsname):
  """
  fpathにあるファイル（.hppを想定）から、enum class [escaname] {...}
  という定義を探し出し、...の間にあるenumのIDの一覧をリストで返す。
  """
  idstrs = []
  ecsBegin = False
  with open(fpath, 'r') as f:    
    for line in f:
      if ecsBegin:
        idMatch = re.search(r' *([A-Z][^,]*),.*', line)
        if idMatch:
          idstrs.append(idMatch.group(1))
        else:
          closeMatch = re.search(r' *};', line)
          if closeMatch:
            return idstrs
      else:
        match = re.search(fr'enum class *{ecsname}', line)
        if match:
          ecsBegin = True
  return idstrs


def update_trans_str_case(fpath, ecsname, funcName, idlist):
  """
  mfg_resource_trans_str.cppの言語ごとのcaseのうち、idlistにあるがエントリが無いIDを
  以下のようなC++コメントとして追加する
  // case ResId::SOME_ID: return "";
  """
  # ステートマシン
  state_init = 0
  state_func_begin = 1
  state_lang_switch = 2
  state_rid_case = 3
  state_deflang_begin = 4
  state_deflang_rid_case = 5
  state_deflang_end = 6
  state = state_init

  lines = []
  case_found = set()
  with open(fpath, 'r', encoding='utf_8_sig') as f:
    for line in f:
      if state == state_init:
        lines.append(line)
        funcMatch = re.search(f'const char\\* {funcName}', line)
        if funcMatch:
          state = state_func_begin
      elif state == state_func_begin:
        lines.append(line)
        langSwitchMatch = re.search(r' *switch\( *lang *\)', line)
        if langSwitchMatch:
          state = state_lang_switch
      elif state == state_lang_switch:        
        lines.append(line)
        ridSwitchMatch = re.search(r' *switch\( *rid *\)', line)
        if ridSwitchMatch:
          state = state_rid_case
          case_found = set()
        else:
          engMatch = re.search(r'case mfg_pal::NL_ENGLISH:', line)
          if engMatch:
            state = state_deflang_begin
      elif state == state_rid_case:
        caseMatch = re.search(f'case {ecsname}::([A-Z][^:]*)', line)
        if caseMatch:
          lines.append(line)
          case_found.add(caseMatch.group(1))
        else:
          defMatch = re.search(r'default:', line)
          if defMatch:
            # case_foundに無いidの一覧を探して、そのコメントを追加
            for id in idlist:
              if id not in case_found:
                lines.append(f'        // case {ecsname}::{id}: return "";\n')
            lines.append(line)
            state = state_lang_switch
          else:
            lines.append(line)
      elif state == state_deflang_begin:
        lines.append(line)
        ridSwitchMatch = re.search(r' *switch\( *rid *\)', line)
        if ridSwitchMatch:
          state = state_deflang_rid_case
          case_found = set()
      elif state == state_deflang_rid_case:
        caseMatch = re.search(f'case {ecsname}::([A-Z][^:]*)', line)
        if caseMatch:
          lines.append(line)
          case_found.add(caseMatch.group(1))
        else:
          defMatch = re.search(r'default:', line)
          if defMatch:
            # case_foundに無いidの一覧を探して、そのコメントを追加
            for id in idlist:
              if id not in case_found:
                lines.append(f'    // case {ecsname}::{id}: return "";\n')
            lines.append(line)
            state = state_deflang_end
          else:
            lines.append(line)
      else:
          # state == state_deflang_end
        lines.append(line)
  return "".join(lines)



